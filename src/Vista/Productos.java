    private void btnEliminarProductoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarProductoActionPerformed
        ProductoDTO pdt = new ProductoDTO();
        pd = new ProductoDAO();
        int fila = tblDatos.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(null,
                    "Seleccione un producto para eliminar");
            return;
        }

        String cod = tblDatos.getValueAt(fila, 0).toString();

        pd.eliminar(cod);

        limpiarTabla();
        listar();
        limpiar();
        JOptionPane.showMessageDialog(null,
                "Producto eliminado correctamente");

    }//GEN-LAST:event_btnEliminarProductoActionPerformed

    private void tblDatosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblDatosMouseClicked

        int fila = tblDatos.getSelectedRow();

        pdt.setCodigo(tblDatos.getValueAt(fila, 0).toString());
        pdt.setNom_pro(tblDatos.getValueAt(fila, 1).toString());
        pdt.setPre_pro(Double.parseDouble(tblDatos.getValueAt(fila, 2).toString()));
        pdt.setStock_pro(Integer.parseInt(tblDatos.getValueAt(fila, 3).toString()));
        pdt.setDescrip_pro(tblDatos.getValueAt(fila, 4).toString());
        
        pdt.setCategoria_pro(tblDatos.getValueAt(fila, 5).toString());

      

        txtCodigoPro.setText(pdt.getCodigo());
        txtNombrePro.setText(pdt.getNom_pro());
        txtPrecioPro.setText("" + pdt.getPre_pro());
        txtStockPro.setText("" + pdt.getStock_pro());
        txtDescriPro.setText(pdt.getDescrip_pro());
        
        cbxCategoria.setSelectedItem(pdt.getCategoria_pro());
        

    }//GEN-LAST:event_tblDatosMouseClicked
    private void limpiar() {
        txtCodigoPro.setText("");
        txtNombrePro.setText("");
        txtPrecioPro.setText("");
        txtStockPro.setText("");
        txtDescriPro.setText("");
        
        cbxCategoria.setSelectedIndex(0);
        
        txtCodigoPro.requestFocus();
    }
    public void limpiarTabla() {
        for (int i = 0; i < mod.getRowCount(); i++) {
            mod.removeRow(i);
            i = i - 1;
        }
    }
