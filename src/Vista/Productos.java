    private void listar() {
        vp = pd.listar();
        for (int i = 0; i < vp.size(); i++) {
            Object[] data = {vp.get(i).getCodigo(), vp.get(i).getNom_pro(), vp.get(i).getPre_pro(), vp.get(i).getStock_pro(), vp.get(i).getDescrip_pro(), vp.get(i).getCategoria_pro()
            };
            mod.addRow(data);

        }
    }

