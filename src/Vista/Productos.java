    private void btnIngresarProductoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarProductoActionPerformed
        SimpleDateFormat fec = new SimpleDateFormat("dd/MM/yyyy");
        ProductoDTO pdt = new ProductoDTO();
        pd = new ProductoDAO();
        pdt.setCodigo(txtCodigoPro.getText());
        pdt.setNom_pro(txtNombrePro.getText());
        pdt.setPre_pro(Double.parseDouble(txtPrecioPro.getText()));
        pdt.setStock_pro(Integer.parseInt(txtStockPro.getText()));
        pdt.setDescrip_pro(txtDescriPro.getText());
        
        pdt.setCategoria_pro(cbxCategoria.getSelectedItem().toString());
        
        pd.insertar(pdt);
        limpiarTabla();
        listar();
        limpiar();

    }//GEN-LAST:event_btnIngresarProductoActionPerformed

